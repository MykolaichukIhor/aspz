#!/bin/bash


# 1. записуємо факт запуску, час та передані аргументи у файл

echo "[$(date)] Виконано ls користувачем $USER з аргументами: $@" >> /tmp/fake_ls_audit.log


# 2. виконання справжньої команди ls

# використовуємо абсолютний шлях /bin/ls, щоб не викликати цей самий скрипт 

# по колу (нескінченна рекурсія), якщо він лежить десь у пріоритетному $PATH.

# "$@" передає всі аргументи, які ввів користувач (наприклад, -l, -a, /etc).

/bin/ls "$@"
